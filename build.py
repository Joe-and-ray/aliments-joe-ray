def cat_name(cat, lang):
    names = C["catalogue"]["categories"]
    if cat not in names:
        print(f"  ! category '{cat}' has no translation in copy.json catalogue.categories; using it as-is")
        return escape(cat)
    return tr(names[cat], lang)


