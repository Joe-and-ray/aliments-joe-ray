def v(path):
    """Cache-busting query string from file content."""
    return path + "?v=" + hashlib.sha1((ROOT / path.lstrip("/")).read_bytes()).hexdigest()[:8]


# SITE_BASE=/repo-name for GitHub Pages project sites (served under a subpath). Empty = site at domain root.
# Any non-root base is treated as a preview: pages get noindex so search engines don't index the prototype.
BASE = os.environ.get("SITE_BASE", "").rstrip("/")


def rebase(html):
    """Prefix root-relative URLs in attributes with BASE."""
    if not BASE:
        return html
    html = re.sub(r'((?:href|src|action|data-home)=")/(?!/)', r"\1" + BASE + "/", html)
    return html.replace("<head>", '<head>\n<meta name="robots" content="noindex">', 1)


