# ---------- helpers ----------
def get(path, lang, **fmt):
    """get('hero.title', 'fr') -> translated, escaped string. {placeholders} filled from fmt."""
    node = C
    for k in path.split("."):
        node = node[k]
    return tr(node, lang, **fmt)


def tr(node, lang, **fmt):
    s = node[lang] if isinstance(node, dict) else node
    for k, v in fmt.items():
        s = s.replace("{" + k + "}", str(v))
    return escape(s)


def tel(n):
    return "tel:+1" + re.sub(r"\D", "", n)


def slug(s):
    s = unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode().lower()
    return re.sub(r"[^a-z0-9]+", "-", s).strip("-")


def fold(s):
    """Search key: lowercase, no accents. Must match fold() in site.js."""
    return unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode().lower()


UNITS = {"KG": "kg", "G": "g", "GR": "g", "ML": "mL", "L": "L", "OZ": "oz", "LB": "lb", "LBS": "lb",
         "X": "x", "CS": "cs", "PK": "pk", "U": "u", "UN": "un"}
SMALL = {"DE", "DU", "DES", "LA", "LE", "LES", "ET", "A", "À", "AU", "AUX", "EN", "OF", "AND", "IN", "WITH", "THE"}


def pretty(name):
    # ponytail: heuristic title-case for the supplier's ALL-CAPS names; raw name stays searchable
    letters = [c for c in name if c.isalpha()]
    if not letters or sum(c.isupper() for c in letters) / len(letters) < 0.7:
        return name
    out = []
    for i, w in enumerate(name.split(" ")):
        core = w.strip("()[]*,")
        if core.upper() in UNITS:
            w = w.replace(core, UNITS[core.upper()])
        elif any(ch.isdigit() for ch in core):
            w = w.lower()
        elif i and core.upper() in SMALL:
            w = w.lower()
        elif len(core) <= 3 and core.isalpha() and core.upper() not in ("PAN", "OIL", "PIE", "BUN", "HOT", "RED", "MIX", "EAU", "JUS", "SEL"):
            pass  # short tokens are usually acronyms (BBQ, IQF, CFIA): keep
        else:
            w = "-".join(p[:1].upper() + p[1:].lower() for p in w.split("-"))
            w = re.sub(r"([’'])(\w)", lambda m: m.group(1) + m.group(2).upper(), w)  # L’Avenue, D’Italia
            w = re.sub(r"([’'])S\b", lambda m: m.group(1) + "s", w)                     # Baker’s
            w = re.sub(r"^([(\[*‘“\"']*)(\w)", lambda m: m.group(1) + m.group(2).upper(), w)
        out.append(w)
    return " ".join(out)


def load_catalogue():
    rows = list(csv.DictReader((ROOT / "content/catalogue.csv").open(encoding="utf-8")))
    cats = {}
    for r in rows:
        r = {k: (v or "").strip() for k, v in r.items()}
        if not r["name"]:
            continue
        cats.setdefault(r["category"], []).append(r)
    for items in cats.values():
        items.sort(key=lambda r: fold(r["name"]))
    return dict(sorted(cats.items(), key=lambda kv: fold(kv[0])))


