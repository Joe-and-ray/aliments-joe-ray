def rebase(html):
    """Prefix root-relative URLs in attributes with BASE."""
    if not BASE:
        return html
    html = re.sub(r'((?:href|src|action|data-home)=")/(?!/)', r"\1" + BASE + "/", html)
    return html.replace("<head>", '<head>\n<meta name="robots" content="noindex">', 1)


